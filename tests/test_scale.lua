-- MicroProfiler at twice the size (Settings > MicroProfiler Size = 2), changed while it is open
check(boot(5), "boots")
local P, S = __T.Profiler, __T.Settings
M.mouse = Vector2.new(960, 900)
S.Set("Show MicroProfiler", 1)
M.step(1 / 60)
local U, I = P.Internals()
eq(U.graph.f.AbsoluteSize.Y, 50, "size 1 = Roblox pixels")
check(S.Set("MicroProfiler Scale", 2), "MicroProfiler Size setting accepts 2")
M.step(1 / 60)
check(S.Set("MicroProfiler Scale", 99) and S.Get("MicroProfiler Scale") == 4, "size is clamped to 4")
S.Set("MicroProfiler Scale", 2)
M.step(1 / 60)
local sc = U.root:FindFirstChildOfClass("UIScale")
check(sc ~= nil and sc.Scale == 2, "UIScale 2 on the root")
local as = U.root.AbsoluteSize
check(as.X == 1920 and as.Y == 1080, "root still covers the screen (" .. tostring(as) .. ")")
local gp, gs = U.graph.f.AbsolutePosition, U.graph.f.AbsoluteSize
-- AbsolutePosition is measured from the bottom of the top bar, so screen y 20 is 20 - inset
check(gp.Y == 20 - M.inset and gs.Y == 100 and gs.X == 1820, "graph doubled: y 20, 1820 x 100 (" .. tostring(gp) .. " / " .. tostring(gs) .. ")")
eq(U.menu.AbsoluteSize.Y, 20, "menu bar 20 px")
-- hover the Mode item at screen position (menuX * 2)
M.mouse = Vector2.new(I.menuX[1] * 2 + 6, 8)
M.step(1 / 60)
check(U.dd.f.Visible, "menu opens with scaled mouse coordinates")
M.mouse = Vector2.new(960, 900)
M.step(1 / 60); M.step(1 / 60)
check(not U.dd.f.Visible, "menu closes")
check(P.IsMouseOver(Vector2.new(100, 15)), "menu bar hit at 2x")
check(P.IsMouseOver(Vector2.new(100, 110)), "graph hit at 2x")
check(not P.IsMouseOver(Vector2.new(100, 130)), "below the graph is the game")
for i = 1, 30 do M.step(0.016) end
M.mouse = Vector2.new(1820 - 2, 60)
M.step(0.016)
check(U.tip.outer.f.Visible, "tooltip at 2x")
check(P.Snapshot().hover == P.Snapshot().recorded, "rightmost bar hovered = newest frame")
-- clicks at 2x: Pause sits at screen x = menuX * 2
M.moveMouse(I.menuX[10] * 2 + 10, 8)
M.step(0.016)
M.click(1)
M.step(0.016)
check(P.IsPaused(), "a click on Pause at 2x pauses")
M.click(1)
M.step(0.016)
check(not P.IsPaused(), "and unpauses")
-- a 4 screen px wobble at 2x is 2 profiler px: still a click (3 px rule in profiler pixels)
M.mouseDown(1)
M.moveMouse(I.menuX[10] * 2 + 14, 8)
M.mouseUp(1)
M.step(0.016)
check(P.IsPaused(), "a 2 px (profiler) wobble is still a click")
M.click(1)
M.step(0.016)
finish()
